/**
 * Mock Juris Web API data: fictional, from the Pre-Bills sample dataset (data.json, one record per line).
 *
 * Shapes follow records.ts, which follows the documented sample responses. Values are a little messy on
 * purpose, the way Juris data tends to be (padded codes, date-times with offsets, "Last, First" names).
 * The data also includes cases a client of the API must handle:
 *   - time that must stay off a pre-bill: a draft, a billed and a non-billable entry per month
 *   - a client with no time
 *   - a non-primary billing address listed before the primary one
 *   - a matter without a bill-to
 *   - a "STD" fee schedule that lists most timekeepers by name and one only by person type,
 *     next to an "ALT" schedule with different rates
 *   - a nested Employee object on each time entry, shared between entries, so responses use
 *     JSON.NET $ref references (it isn't stored in data.json; it is linked up when the data loads)
 *
 * data.json was generated by the Pre-Bills repo's backend/mock/juris-api/data.ts (seedToMockJuris).
 * The smoke test's expected figures come from it, so change it only on purpose.
 */
import { readFileSync } from "node:fs";
import type {
  ApiActivityCode,
  ApiBillingAddress,
  ApiBillTo,
  ApiClient,
  ApiEmployee,
  ApiFeeSchedule,
  ApiMatter,
  ApiMatterResponsibleTimekeeper,
  ApiPracticeClass,
  ApiTaskCode,
  ApiTimeEntry,
} from "./records.js";

/** Time entries carry a nested Employee, as in the documented sample. */
export type MockTimeEntry = ApiTimeEntry & { Employee: ApiEmployee };

export interface MockJurisData {
  clients: ApiClient[];
  billingAddresses: ApiBillingAddress[];
  billTos: ApiBillTo[];
  matters: ApiMatter[];
  responsibleTimekeepers: ApiMatterResponsibleTimekeeper[];
  employees: ApiEmployee[];
  feeSchedules: ApiFeeSchedule[];
  practiceClasses: ApiPracticeClass[];
  activityCodes: ApiActivityCode[];
  taskCodes: ApiTaskCode[];
  timeEntries: MockTimeEntry[];
}

/** The JURIS_API_PERSON_TYPES value that labels the mock's person type codes. */
export const MOCK_PERSON_TYPES = "P=Partner,OC=Of Counsel,SA=Senior Associate,A=Associate,PL=Paralegal";
export const MOCK_STANDARD_FEE_SCHEDULE = "STD";

/** A fresh copy of the mock data (the mock's POST /api/TimeEntries adds to it). */
export function loadMockData(): MockJurisData {
  const raw = JSON.parse(readFileSync(new URL("./data.json", import.meta.url), "utf8")) as Omit<MockJurisData, "timeEntries"> & { timeEntries: ApiTimeEntry[] };
  const employee = new Map(raw.employees.map((e) => [e.EmpSysNbr, e]));
  return {
    ...raw,
    timeEntries: raw.timeEntries.map((t) => ({ ...t, Employee: employee.get(t.TimekeeperSysNbr)! })),
  };
}
